// Acentos y eñes: se arman a partir de la letra base.
const ACUTE_UP = ['..#..', '.#...'];
const ACUTE_LOW4 = ['..#.', '.#..'];
function withTop(base: string, top: string[]): GlyphDef {
  const b = GLYPHS[base];
  return { ...b, top };
}
function withLowAccent(base: string, acc: string[]): GlyphDef {
  const b = GLYPHS[base];
  const rows = [...b.rows];
  rows[0] = acc[0];
  rows[1] = acc[1];
  return { ...b, rows };
}

